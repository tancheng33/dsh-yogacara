/**
 * Regenerate `docs/appraisal.md` from the rules themselves.
 *
 * The appraisal rules are the plugin's contestable claim, so they have to be
 * readable without reading TypeScript — and a hand-written table would drift
 * from the code within two commits. Run after changing anything in
 * `src/citta.ts`; CI fails when the committed doc differs from this output.
 */
import { writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import {
  DEFENSIVE_GRIP, GATE_RULES, SEED_ENTRENCHED,
  STREAK_CHURN, STREAK_CONCEIT, STREAK_DULL,
} from '../src/citta.ts'
import { CAITASIKAS, CONSCIOUSNESSES, caitasika } from '../src/caitasika.ts'
import { DEFAULT_TUNING } from '../src/types.ts'

const term = id => {
  const found = caitasika(id)
  return found === undefined ? id : `${found.chinese} ${found.id}`
}
const rule = weights => Object.entries(weights)
  .sort((a, b) => b[1] - a[1])
  .map(([id, weight]) => `${term(id)} ${weight}`)
  .join(' · ')

const gates = CONSCIOUSNESSES.filter(one => one.id in GATE_RULES)

/**
 * Render the whole document.
 * @returns the markdown, exactly as `docs/appraisal.md` must contain it.
 */
export function renderAppraisalDoc() {
  const lines = [
    '# Appraisal rules',
    '',
    '<!-- GENERATED by scripts/generate-appraisal-doc.mjs — do not edit by hand. -->',
    '',
    'What one contact does to the mind, in full. These are heuristics chosen by',
    'this project, not doctrine: the classical sources say which factors exist and',
    'what counteracts what, and say nothing about how hard a failing test should',
    'land. Every number below is arguable, and this page exists so it can be',
    'argued with without reading TypeScript.',
    '',
    '## The five gates',
    '',
    'Every contact arrives through one gate, and the gate decides both the feeling',
    'and the factors. The same failure through `ear` (being corrected) and through',
    '`body` (a non-zero exit) is not the same event for the mind that receives it.',
    '',
    '| gate | what it is | favorable | adverse |',
    '|---|---|---|---|',
    ...gates.map(one =>
      `| ${one.chinese} \`${one.id}\` | ${one.gloss} | ${rule(GATE_RULES[one.id].favorable)} | ${rule(GATE_RULES[one.id].adverse)} |`),
    '',
    'Weights are scaled by the contact\'s intensity and combined saturatingly, so a',
    'mind can be fully irritated but never doubly irritated.',
    '',
    '## Feeling',
    '',
    '`body` and `tongue` are bodily seats, so they yield 苦 / 乐; `eye`, `ear`, and',
    '`nose` are read cognitively, so they yield 忧 / 喜. A neutral contact is 舍.',
    'Mental feeling is the stronger of the two (±0.8 against ±0.6) before intensity',
    'scaling — being told you are wrong lands harder than a command exiting 1.',
    '',
    '## Universal factors',
    '',
    'Present in every contact regardless of gate or outcome: 触 sparsa 0.6,',
    '作意 manaskara 0.4, 受 vedana 0.5, 思 cetana 0.3.',
    '',
    '## Thresholds',
    '',
    '| constant | value | what it decides |',
    '|---|---|---|',
    `| \`STREAK_CONCEIT\` | ${STREAK_CONCEIT} | a favorable run this long starts stirring 憍 mada and 放逸 pramada, and raises 我慢 |`,
    `| \`STREAK_CHURN\` | ${STREAK_CHURN} | an adverse run this long starts stirring 掉举 auddhatya and 恨 upanaha |`,
    `| \`STREAK_DULL\` | ${STREAK_DULL} | an adverse run this long starts stirring 昏沉 styana, 懈怠 kausidya, and 疑 vicikitsa |`,
    `| \`SEED_ENTRENCHED\` | ${SEED_ENTRENCHED} | a seed re-perfumed adversely this often reads as a position being defended: 恶见 drsti, and 我见 rises |`,
    `| \`DEFENSIVE_GRIP\` | ${DEFENSIVE_GRIP} | above this grip a correction is met with 覆 mraksa + 嗔 pratigha instead of 惭 hri + 愧 apatrapya |`,
    '',
    'The last row is the one worth staring at. It is where the model stops being a',
    'mood tracker: the object is not met bare, it is met through the self that',
    'receives it, so the same correction becomes two different mental events',
    'depending on how tightly the agent is currently holding its own record.',
    '',
    '## Epistemic status of a reading',
    '',
    'When a contact carries a `nature`, it moves self-delusion directly — this is',
    'the one place the agent grades itself.',
    '',
    '| nature | factors stirred | 我痴 |',
    '|---|---|---|',
    '| 遍计所执 `parikalpita` (assumed) | 痴 moha 0.3 | +0.10 |',
    '| 依他起 `paratantra` (inferred) | 伺 vicara 0.25 | unchanged |',
    '| 圆成实 `parinispanna` (verified) | 无痴 amoha 0.4 · 慧 prajna 0.3 | −0.12 |',
    '',
    'A favorable contact through `tongue` or `body` lowers 我痴 by a further 0.05,',
    'because running it and touching it are the gates that can be wrong about the',
    'world. Reading and being told cannot, however convincing they feel.',
    '',
    '## Self-grasping',
    '',
    '| movement | when |',
    '|---|---|',
    '| 我慢 −0.12, 我见 −0.06 | a correction received while the grip is loose |',
    '| 我慢 +0.05, 我见 +0.05 | the same correction while the grip is tight |',
    `| 我慢 +0.05 per excess win | a favorable run at or past \`STREAK_CONCEIT\`, capped at +0.2 |`,
    `| 我见 +0.10 | an adverse contact on a seed at or past \`SEED_ENTRENCHED\` |`,
    '| 我爱 +0.08 | the object is the agent\'s own output (`self:` situation) |',
    '| 我爱 −0.03 | any other object |',
    '',
    '## Decay',
    '',
    '| what | half-life |',
    '|---|---|',
    `| a mental factor, and the feeling's arousal | ${DEFAULT_TUNING.halfLifeMs / 60000} minutes |`,
    '| self-grasping | ten times a factor\'s — a standing disposition, not a mood |',
    `| a seed's potency | ${DEFAULT_TUNING.seedHalfLifeMs / 86400000} days |`,
    '',
    `Anything below ${DEFAULT_TUNING.floor} is dropped rather than carried as noise.`,
    '',
    '## Transformation',
    '',
    'Which wisdom answers an affliction follows from what kind of affliction it is:',
    'not-seeing turns through 妙观察智, distorting the record through 大圆镜智,',
    'slackness through 成所作智, and everything else — grabbing, recoiling, and all',
    'four self-graspings — through 平等性智.',
    '',
    `The antidote itself is never invented here: it is the classical pairing carried on each of the ${CAITASIKAS.length} factors.`,
    '',
  ]
  return lines.join('\n')
}

/** The path the document lives at. */
export const APPRAISAL_DOC = fileURLToPath(new URL('../docs/appraisal.md', import.meta.url))

// Writing is the script's job; importing it for the freshness check is not.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(APPRAISAL_DOC, renderAppraisalDoc())
}
